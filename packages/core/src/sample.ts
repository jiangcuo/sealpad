/**
 * 示例印章：只用于体验盖章流程，文字明确标注「仅供体验」。
 * 正式的印章设计器（文字转路径、预设模板）在路线图第二阶段。
 */

export interface RoundSealOptions {
  /** 沿上方弧线排列的文字 */
  arcText: string;
  /** 五角星下方的横排文字 */
  bottomText?: string;
  color?: string;
  /** 输出 SVG 的像素尺寸 */
  size?: number;
}

const FONT_FAMILY = "'Source Han Serif SC','Noto Serif CJK SC','Songti SC','STSong','SimSun',serif";

function escapeXml(s: string): string {
  return s.replace(/[<>&'"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[c]!);
}

function starPath(cx: number, cy: number, outer: number): string {
  const inner = outer * 0.382;
  const pts: string[] = [];
  for (let i = 0; i < 10; i++) {
    const r = i % 2 === 0 ? outer : inner;
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    pts.push(`${(cx + r * Math.cos(a)).toFixed(2)},${(cy + r * Math.sin(a)).toFixed(2)}`);
  }
  return `M${pts.join('L')}Z`;
}

export function roundSealSvg(opts: RoundSealOptions): string {
  const size = opts.size ?? 400;
  const color = opts.color ?? '#d7261e';
  const c = 200;
  const chars = Array.from(opts.arcText);
  const span = Math.min(250, 26 * chars.length);
  const start = -90 - span / 2;
  const step = chars.length > 1 ? span / (chars.length - 1) : 0;
  const textRadius = 142;
  const arc = chars
    .map((ch, i) => {
      const deg = start + i * step;
      const rad = (deg * Math.PI) / 180;
      const x = c + textRadius * Math.cos(rad);
      const y = c + textRadius * Math.sin(rad);
      return `<text x="${x.toFixed(2)}" y="${y.toFixed(2)}" transform="rotate(${(deg + 90).toFixed(2)} ${x.toFixed(2)} ${y.toFixed(2)})">${escapeXml(ch)}</text>`;
    })
    .join('');
  const bottom = opts.bottomText
    ? `<text x="${c}" y="${c + 110}" font-size="36">${escapeXml(opts.bottomText)}</text>`
    : '';
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 400 400">`,
    '<metadata>Generated by SealPad (印台). Sample only, not a real seal.</metadata>',
    `<g fill="${color}" font-family="${FONT_FAMILY}" font-size="46" font-weight="700" text-anchor="middle" dominant-baseline="central">`,
    `<circle cx="${c}" cy="${c}" r="188" fill="none" stroke="${color}" stroke-width="12"/>`,
    `<path d="${starPath(c, c, 62)}"/>`,
    arc,
    bottom,
    '</g></svg>',
  ].join('');
}

export const SAMPLE_SEAL = {
  name: '示例印章（仅供体验）',
  svg: () => roundSealSvg({ arcText: '印台开源项目示例印章', bottomText: '仅供体验' }),
  widthMm: 40,
};

export function createId(): string {
  const c = (globalThis as { crypto?: Crypto }).crypto;
  if (c?.randomUUID) return c.randomUUID();
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}
